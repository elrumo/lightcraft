//! `cargo xtask swift-strings [<derived-data>]`: the SwiftUI app's string tables
//! (`Sources/LightCraftApp/Localization/<lang>.lproj/Localizable.strings`), made from the egui catalogs
//! (`crates/ui-egui/locales/<code>.json` and `-formats.json`) and the app's own
//! (`apps/lightcraft-ios-swift/locales/<code>.json`), so a translation is written once.
//!
//! The keys the app uses are in `apps/lightcraft-ios-swift/locales/keys.json`. Given an Xcode derived-data
//! folder of a build made with `SWIFT_EMIT_LOC_STRINGS=YES`, the command first refreshes that list from
//! the compiler's `*.stringsdata`. Every egui message goes into the tables too: the engine's labels
//! (controls, commands, filters) reach the app in English and are looked up at run time.
//!
//! A key is translated by, in order: the app's catalog; the egui catalog; the egui catalog ignoring case
//! and a trailing `…`, `.` or `:`; an egui format message with the same text around its placeholders
//! (`{count}` ↔ `%lld`, numbered so a translation may reorder them). What is left is listed: the
//! app's catalog takes those.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// egui's locale code, the iOS localization it becomes.
const LANGUAGES: &[(&str, &str)] = &[
    ("zh-hans", "zh-Hans"),
    ("zh-hant", "zh-Hant"),
    ("ja", "ja"),
    ("pt-br", "pt-BR"),
    ("es", "es"),
    ("de", "de"),
    ("ru", "ru"),
    ("fr", "fr"),
    ("uk", "uk"),
];

const HEADER: &str =
    "/* Generated by `cargo xtask swift-strings` from crates/ui-egui/locales and apps/lightcraft-ios-swift/locales: edit those. */\n";

pub fn run(root: &Path, args: &[&str]) -> Result<(), String> {
    let app = root.join("apps/lightcraft-ios-swift");
    let keys_path = app.join("locales/keys.json");
    if let Some(dd) = args.iter().find(|a| !a.starts_with("--")) {
        let keys = extract(Path::new(dd), &app.join("LightCraft/Sources/LightCraftApp"))?;
        if keys.is_empty() {
            return Err(format!("no *.stringsdata under {dd}: build with SWIFT_EMIT_LOC_STRINGS=YES"));
        }
        write_json(&keys_path, &serde_json::to_value(&keys).map_err(|e| e.to_string())?)?;
        println!("{} keys → {}", keys.len(), keys_path.display());
    }
    let keys: BTreeSet<String> = serde_json::from_str(&read(&keys_path)?).map_err(|e| format!("{}: {e}", keys_path.display()))?;
    let out = app.join("LightCraft/Sources/LightCraftApp/Localization");
    let mut report = String::new();
    for (code, lproj) in LANGUAGES {
        let plain = catalog(&root.join(format!("crates/ui-egui/locales/{code}.json")))?;
        let formats = catalog(&root.join(format!("crates/ui-egui/locales/{code}-formats.json")))?;
        let own = catalog(&app.join(format!("locales/{code}.json"))).unwrap_or_default();
        let (table, missing) = table(&keys, &plain, &formats, &own);
        write(&out.join(format!("{lproj}.lproj/Localizable.strings")), &strings_file(&table))?;
        if !missing.is_empty() {
            let _ = writeln!(report, "{code}: {} untranslated", missing.len());
            if args.contains(&"--missing") {
                for k in &missing {
                    let _ = writeln!(report, "  {k:?}");
                }
            }
        }
    }
    // the source language: its own catalog only (plural fixes and the like)
    let en = catalog(&app.join("locales/en.json")).unwrap_or_default();
    write(&out.join("en.lproj/Localizable.strings"), &strings_file(&en))?;
    print!("{report}");
    Ok(())
}

/// The keys of the app's `Localizable` table in the compiler's `*.stringsdata` under `dd`, for sources
/// under `sources`.
fn extract(dd: &Path, sources: &Path) -> Result<BTreeSet<String>, String> {
    let mut files = Vec::new();
    walk(dd, &mut files, 0);
    let mut keys = BTreeSet::new();
    for f in files {
        let Ok(v) = serde_json::from_str::<serde_json::Value>(&read(&f)?) else { continue };
        if !v["source"].as_str().is_some_and(|s| Path::new(s).starts_with(sources)) {
            continue;
        }
        for row in v["tables"]["Localizable"].as_array().into_iter().flatten() {
            if let Some(k) = row["key"].as_str().filter(|k| !k.trim().is_empty()) {
                keys.insert(k.to_string());
            }
        }
    }
    Ok(keys)
}

fn walk(dir: &Path, out: &mut Vec<PathBuf>, depth: usize) {
    let Ok(entries) = std::fs::read_dir(dir) else { return };
    for e in entries.flatten() {
        let p = e.path();
        if p.is_dir() && depth < 24 {
            walk(&p, out, depth + 1);
        } else if p.extension().is_some_and(|x| x == "stringsdata") {
            out.push(p);
        }
    }
}

/// One language's table: every egui message, then the app's keys; and the keys nothing translates.
fn table(
    keys: &BTreeSet<String>,
    plain: &BTreeMap<String, String>,
    formats: &BTreeMap<String, String>,
    own: &BTreeMap<String, String>,
) -> (BTreeMap<String, String>, Vec<String>) {
    // messages with a context (`"<context>|<message>"`) are egui's alone
    let mut table: BTreeMap<String, String> = plain.iter().filter(|(k, _)| !k.contains('|')).map(|(k, v)| (k.clone(), v.clone())).collect();
    let loose: BTreeMap<String, &String> = plain.keys().filter(|k| !k.contains('|')).map(|k| (loosen(k), k)).collect();
    let shapes: BTreeMap<String, &String> = formats.keys().map(|k| (shape(&rust_holes(k).0), k)).collect();
    let mut missing = Vec::new();
    for key in keys {
        let specs = swift_specs(key);
        if let Some(t) = own.get(key) {
            if same_conversions(&specs, t) {
                table.insert(key.clone(), t.clone());
                continue;
            }
            missing.push(format!("{key} (its translation's conversions differ)"));
            continue;
        }
        if specs.is_empty() {
            if plain.contains_key(key) {
                continue;
            }
            if let Some(t) = loose.get(&loosen(key)).and_then(|k| plain.get(*k).map(|t| adapt(key, k, t))) {
                table.insert(key.clone(), t);
                continue;
            }
        } else if let Some(t) = shapes.get(&shape(&swift_text(key))).and_then(|k| formats.get(*k).and_then(|t| convert(k, t, &specs))) {
            table.insert(key.clone(), t);
            continue;
        }
        missing.push(key.clone());
    }
    (table, missing)
}

/// A message compared loosely: lower case, without a trailing `…`, `.`, `:` or spaces.
fn loosen(s: &str) -> String {
    s.trim_end_matches(['…', '.', ':', ' ']).to_lowercase()
}

/// `t` (the translation of `source`) as `key` needs it: its trailing `…` and an initial capital
/// when `key` has them and `source` doesn't.
fn adapt(key: &str, source: &str, t: &str) -> String {
    let mut out = t.trim_end_matches(['…', '.', ':', ' ']).to_string();
    if t.ends_with('…') || t.ends_with('.') || t.ends_with(':') {
        // the translation's own punctuation (`:`, `。`) is kept when the key keeps the source's
        if key.ends_with(source.chars().last().unwrap_or(' ')) {
            out = t.to_string();
        }
    }
    let tail: String = key.chars().rev().take_while(|c| matches!(c, '…' | '.' | ':')).collect();
    if !tail.is_empty() && !out.ends_with(['…', '.', ':', '。', '：']) {
        out.extend(tail.chars().rev());
    }
    let upper = key.chars().next().is_some_and(char::is_uppercase) && source.chars().next().is_some_and(char::is_lowercase);
    if upper {
        let mut c = out.chars();
        if let Some(first) = c.next() {
            out = first.to_uppercase().chain(c).collect();
        }
    }
    out
}

/// The conversions of a Swift format key, in order (`%lld`, `%@`, `%1$@`…; `%%` is a percent sign).
fn swift_specs(key: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut chars = key.chars().peekable();
    while let Some(c) = chars.next() {
        if c != '%' {
            continue;
        }
        if chars.peek() == Some(&'%') {
            chars.next();
            continue;
        }
        let mut spec = String::new();
        while let Some(&n) = chars.peek() {
            chars.next();
            if n == '$' {
                spec.clear();
                continue;
            }
            spec.push(n);
            if n.is_ascii_alphabetic() && n != 'l' && n != 'h' || n == '@' {
                break;
            }
        }
        out.push(spec);
    }
    out
}

/// A translation takes the key's arguments: the same conversions, in any order.
fn same_conversions(specs: &[String], t: &str) -> bool {
    let (mut a, mut b) = (specs.to_vec(), swift_specs(t));
    a.sort();
    b.sort();
    a == b
}

/// A Swift key's text with each conversion as `\0` and `%%` as `%`.
fn swift_text(key: &str) -> String {
    let mut out = String::new();
    let mut chars = key.chars().peekable();
    while let Some(c) = chars.next() {
        if c != '%' {
            out.push(c);
            continue;
        }
        if chars.peek() == Some(&'%') {
            chars.next();
            out.push('%');
            continue;
        }
        for n in chars.by_ref() {
            if n.is_ascii_alphabetic() && n != 'l' && n != 'h' || n == '@' {
                break;
            }
        }
        out.push('\0');
    }
    out
}

/// A Rust format string's text with each `{…}` as `\0` (`{{` `}}` as braces), and what was in them.
fn rust_holes(s: &str) -> (String, Vec<String>) {
    let (mut text, mut holes) = (String::new(), Vec::new());
    let mut chars = s.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '{' if chars.peek() == Some(&'{') => {
                chars.next();
                text.push('{');
            }
            '}' if chars.peek() == Some(&'}') => {
                chars.next();
                text.push('}');
            }
            '{' => {
                let inner: String = chars.by_ref().take_while(|&n| n != '}').collect();
                holes.push(inner);
                text.push('\0');
            }
            _ => text.push(c),
        }
    }
    (text, holes)
}

/// Text compared for a match (straight and curly quotes alike).
fn shape(s: &str) -> String {
    s.replace(['“', '”'], "\"").replace('’', "'")
}

/// The egui format message `t` (translating `source`) as a Swift format string: each `{name}` becomes
/// the numbered conversion of the source's placeholder with that name (unnamed ones in order).
fn convert(source: &str, t: &str, specs: &[String]) -> Option<String> {
    let (_, holes) = rust_holes(source);
    if holes.len() != specs.len() {
        return None;
    }
    let name = |h: &str| h.split(':').next().unwrap_or("").to_string();
    let names: Vec<String> = holes.iter().map(|h| name(h)).collect();
    let mut out = String::new();
    let mut unnamed = names.iter().enumerate().filter(|(_, n)| n.is_empty()).map(|(i, _)| i);
    let mut chars = t.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '{' if chars.peek() == Some(&'{') => {
                chars.next();
                out.push('{');
            }
            '}' if chars.peek() == Some(&'}') => {
                chars.next();
                out.push('}');
            }
            '{' => {
                let inner: String = chars.by_ref().take_while(|&n| n != '}').collect();
                let n = name(&inner);
                // `{}` in order, `{0}` by position, `{count}` by name
                let i = match n.parse::<usize>() {
                    _ if n.is_empty() => unnamed.next()?,
                    Ok(k) => k,
                    Err(_) => names.iter().position(|m| *m == n)?,
                };
                let _ = write!(out, "%{}${}", i + 1, specs.get(i)?);
            }
            '%' => out.push_str("%%"),
            _ => out.push(c),
        }
    }
    Some(out)
}

fn strings_file(table: &BTreeMap<String, String>) -> String {
    let esc = |s: &str| s.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n");
    let mut out = String::from(HEADER);
    for (k, v) in table {
        let _ = writeln!(out, "\"{}\" = \"{}\";", esc(k), esc(v));
    }
    out
}

fn catalog(path: &Path) -> Result<BTreeMap<String, String>, String> {
    serde_json::from_str(&read(path)?).map_err(|e| format!("{}: {e}", path.display()))
}

fn read(path: &Path) -> Result<String, String> {
    std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

fn write(path: &Path, text: &str) -> Result<(), String> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    }
    std::fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))
}

fn write_json(path: &Path, v: &serde_json::Value) -> Result<(), String> {
    let text = serde_json::to_string_pretty(v).map_err(|e| e.to_string())?;
    write(path, &(text + "\n"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn formats_become_numbered_conversions() {
        assert_eq!(swift_specs("Delete “%@” from %lld photos? 100%%"), ["@", "lld"]);
        assert_eq!(swift_text("%lld × %lld%@"), "\0 × \0\0");
        let (text, holes) = rust_holes("Delete \"{name}\" from {count} photos?");
        assert_eq!((shape(&text), holes), (shape(&swift_text("Delete “%@” from %lld photos?")), vec!["name".to_string(), "count".to_string()]));
        // a translation may put them the other way round
        let t = convert("Delete \"{name}\" from {count} photos?", "{count} fotos sin «{name}» (100%)", &["@".into(), "lld".into()]);
        assert_eq!(t.as_deref(), Some("%2$lld fotos sin «%1$@» (100%%)"));
        assert_eq!(convert("{} of {}", "{} de {}", &["lld".into(), "lld".into()]).as_deref(), Some("%1$lld de %2$lld"));
        assert_eq!(convert("{} of {}", "{}", &["lld".into()]), None);
        assert_eq!(convert("{} of 4", "已画 {0} 条", &["lld".into()]).as_deref(), Some("已画 %1$lld 条"));
        assert!(same_conversions(&swift_specs("%@ of %lld"), "%2$lld de %1$@"));
        assert!(!same_conversions(&swift_specs("%@ of %lld"), "%@ de %@"));
    }

    #[test]
    fn loose_matches_keep_the_keys_punctuation_and_capital() {
        assert_eq!(adapt("Delete…", "Delete", "Eliminar"), "Eliminar…");
        assert_eq!(adapt("Any", "any", "cualquiera"), "Cualquiera");
        assert_eq!(adapt("Licence", "Licence:", "Licencia:"), "Licencia");
    }
}
